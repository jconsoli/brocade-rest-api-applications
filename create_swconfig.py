def _common_worksheet_setup(chassis_obj, wb, sheet_index, sheet_d):
    """Common worksheet setup: Create worksheet, set sheet name, column widths, hidden status, and add data validation

    :param chassis_obj: Chassis or switch object.
    :type chassis_obj: brcddb.classes.chassis.ChassisObj, brcddb.classes.switch.SwitchObj
    :param wb: Excel workbook object
    :type wb: openpyxl.workbook.workbook.Workbook
    :param sheet_index: Index sheet is to be inserted after
    :type sheet_index: int
    :param sheet_d: Common worksheet definitions. See _instructions_sheet_d for an example.
    :type sheet_d: dict
    :return: Excel worksheet
    :rtype: openpyxl.worksheet.worksheet.Worksheet
    """
    global _dv_d

    # Set up the worksheet
    sheet = wb.create_sheet(index=sheet_index, title=sheet_d['name'])
    sheet.page_setup.paperSize = sheet.PAPERSIZE_LETTER
    sheet.sheet_state = sheet_d['status']
    dv_d = dict()  # Used for tracking data validations added to this sheet.
    col = 1
    for col_width in sheet_d.get('col_width_l', list()):
        sheet.column_dimensions[xl.get_column_letter(col)].width = col_width
        col += 1

    # Add the content
    row = 1
    for col_l in sheet_d['row_l']:
        col = 1
        for col_d in col_l:
            row_height = col_d.get('h')
            if isinstance(row_height, int):
                sheet.row_dimensions[row].height = row_height
            excel_util.cell_update(
                sheet,
                row,
                col,
                col_d.get('buf')(chassis_obj) if callable(col_d.get('buf')) else col_d.get('buf'),
                font=col_d['f'],
                align=col_d['a'],
                dv=_dv_d[col_d.get('dv', 'none')](sheet, dv_d)
            )
            merge_col = col_d.get('m', 1)
            if merge_col > 1:
                sheet.merge_cells(start_row=row, start_column=col, end_row=row, end_column=col+merge_col)
            col += merge_col
        row += 1

    return sheet


def _switch_worksheet_setup(switch_obj, wb, sheet_index, sheet_d):
    """Common worksheet setup: Create worksheet, set sheet name, column widths, hidden status, and add data validation

    :param switch_obj: Switch object.
    :type switch_obj: brcddb.classes.switch.SwitchObj
    :param wb: Excel workbook object
    :type wb: openpyxl.workbook.workbook.Workbook
    :param sheet_index: Index sheet is to be inserted after
    :type sheet_index: int
    :param sheet_d: Common worksheet definitions. See _instructions_sheet_d for an example.
    :type sheet_d: dict
    :return: sheet: openpyxl.worksheet.worksheet.Worksheet, fid: FID cell reference, did: DID cell reference
    :rtype: dict
    """

    # Fill out the worksheet template
    temp_d = copy.deepcopy(sheet_d)
    temp_d['name'] = 'Switch_' + str(switch_obj.r_fid())

    # Figure out the cell references for FID and DID
    row, fid, did = 1, None, None
    for col_l in temp_d['row_l']:
        for col_d in col_l:
            if col_d.get('buf', '') == 'Fabric ID (FID)':
                fid = temp_d['name'] + '!B' + str(row)
            elif col_d.get('buf', '') == 'Domain ID (DID)':
                did = temp_d['name'] + '!B' + str(row)
        row += 1

    return dict(sheet=_common_worksheet_setup(switch_obj, wb, sheet_index, temp_d), fid=fid, did=did)



_dv_common_e = ' Please use pull down menu to pick an appropriate value.'  # Appended to all data validation error msgs


def _dv_yn(sheet, dv_d):
    """Returns a data validation for "Yes/No". Adds the data validation to the worksheet if not already present.
    
    :param sheet: Excel worksheet object.
    :type sheet: openpyxl.worksheet.worksheet.Worksheet
    :param dv_d: Used to determine if a data validation was already created for a sheet. See _dv_d for details
    :type dv_d: dict
    :return: DataValidation
    :rtype: openpyxl.worksheet.datavalidation.DataValidation
    """
    global _dv_common_e

    dv = dv_d.get('yn')
    if dv is None:
        dv = DataValidation(type='list', formula1='"Yes,No"', allow_blank=False)
        dv.errorTitle = 'Invalid Entry'
        dv.error = 'Value must be "Yes" or "No".' + _dv_common_e
        dv_d['yn'] = dv
        sheet.add_data_validation(dv)
    return dv



def _determine_slots(chassis_obj):
    """Determines the slot types and number of ports in each slot. Return is a list of dictionaries as follows:

    +-------+-------+-------------------------------------------+
    | Key   | Type  | Description                               |
    +=======+=======+===========================================+
    | slot  | int   | Slot number. 0 for fixed port switches.   |
    +-------+-------+-------------------------------------------+
    | type  | str   | Port card type. Key to _slot_sheet_d      |
    +-------+-------+-------------------------------------------+
    | ports | list  | List of port objects                      |
    +-------+-------+-------------------------------------------+

    :param chassis_obj: Chassis Object
    :type chassis_obj: brcddb_classes.chassis.ChassisObj
    :return: List of slot dictionaries. See function header description for details
    :rtype: list
    """
    global _sw_blade_type_d, _fc_port_count_d

    chassis_name = brcddb_chassis.best_chassis_name(chassis_obj)  # Used for error reporting only
    slot_d = dict()  # Key is the slot number. Value is a dictionary as specified in the function header
    sw_blade_type_d = _sw_blade_type_d if brcddb_chassis.gen(chassis_obj) < 8 else _sw_blade_type_g8_d

    # Find all the blades in the chassis that are port blades
    for blade_d in chassis_obj.r_get(brcdapi_util.fru_blade, list()):
        blade_type = blade_d.get('blade-type')
        if blade_type == 'unknown':
            continue  # Typical of vacant slot
        blade_type_d = sw_blade_type_d.get('None') if blade_type is None else sw_blade_type_d.get(blade_type, 'None')
        if blade_type_d['supported'] == False:
            buf = 'Unsupported blade type: ' + str(blade_type) + ' Slot: ' + str(blade_d.get('slot-number', 0))
            buf += ' Chassis: ' + chassis_name + '. Skipping.'
            brcdapi_log.log(buf, True)
            continue
        if blade_type_d['skip']:
            continue
        if blade_d.get('fc-port-count') is None:
            blade_d['fc-port-count'] = _fc_port_count_d[blade_d.get('blade-id', 0)]
            if blade_d['fc-port-count'] == 0:
                brcdapi_log.log(['ERROR: Could not determine port count for:', pprint.pformat(blade_d)], echo=True)
                continue
        if blade_d['fc-port-count'] == 0:
            continue  # We get here when a new board type is introduced that doesn't have any FC ports
        slot_num = blade_d['slot-number']
        slot_d[slot_num] = dict(slot=slot_num, ports=list())
        if slot_num == 0:
            slot_d[slot_num]['type'] = 'fixed_64' if blade_d['fc-port-count'] == 64 else 'fixed_128'
        else:
            slot_d[slot_num]['type'] = blade_type_d.get(blade_d['fc-port-count'])

    # Determine which port goes with which slot.
    for port_obj in chassis_obj.r_port_objects():
        sp_d = gen_util.slot_port_dict(port_obj.r_obj_key())
        slot_d[sp_d['slot']]['ports'].append(port_obj)

    # Map the port type (key) to _slot_sheet_d
    # try/except was put here due to a defect in a very early FOS version. I don't think it was ever released.
    try:
        for blade_d in chassis_obj.r_get(brcdapi_util.fru_blade, list()):
            blade_type = blade_d.get('blade-type')
            if blade_type == 'unknown':
                continue  # Typical of vacant slot
            blade_type_d = sw_blade_type_d.get('None') if blade_type is None \
                else sw_blade_type_d.get(blade_type, 'None')
            if not blade_type_d['supported']:
                buf = 'Unsupported blade type: ' + str(blade_type) + ' Slot: ' + str(blade_d.get('slot-number', 0))
                buf += ' Chassis: ' + chassis_name + '. Skipping.'
                brcdapi_log.log(buf, True)
                continue
            if blade_type_d['skip']:
                continue
            slot_num = blade_d['slot-number']
            if slot_num == 0:
                slot_d[slot_num]['type'] = 'fixed_64' if blade_d['fc-port-count'] == 64 else 'fixed_128'
            else:
                slot_d[slot_num]['type'] = blade_type_d.get(blade_d['fc-port-count'])
    except KeyError:
        brcdapi_log.exception(pprint.pformat(blade_d), echo=True)

    slot_d_key_l = [int(key) for key in slot_d.keys()]
    slot_d_key_l.sort()  # Although not necessary, humans like to see the workbook with slots in order
    return [slot_d[key] for key in slot_d_key_l]


def _add_slot(wb, sheet_index, slot, slot_type, port_obj_l):
    """Adds a port slot sheet to the workbook

    :param wb: Excel workbook object
    :type wb: openpyxl.workbook.workbook.Workbook
    :param sheet_index: Index sheet is to be inserted after
    :type sheet_index: int
    :param slot: Slot number
    :type slot: int
    :param slot_type: Key in _slot_sheet_d for the applicable slot type.
    :type slot_type: str
    :return ec: Exit code
    :rtype ec: int
    """
    global _slot_sheet_d, _white_bold_font, _align_wrap_c, _fill_slot, _border_thin, _std_font, _fill_asic_d

    ec = brcddb_common.EXIT_STATUS_OK

    # Create the slot sheet and perform basic sheet setup
    title = 'Slot ' + str(slot)
    sheet = wb.create_sheet(index=sheet_index, title=title)
    sheet.page_setup.paperSize = sheet.PAPERSIZE_LETTER
    sheet.page_setup.orientation = sheet.ORIENTATION_LANDSCAPE
    dv_d = dict()  # Used for tracking data validations added to this sheet.
    row, col = 1, 2
        
    # Add the slot number in the first row
    excel_util.cell_update(
        sheet,
        row,
        col,
        title.upper(),
        font=_white_bold_font,
        align=_align_wrap_c,
        fill=_fill_slot,
        border=_border_thin)
    sheet.merge_cells(start_row=row, start_column=col, end_row=row, end_column=len(_slot_sheet_d[slot_type]['hdr']))

    # Add the headers and set the column width
    row, col = row + 1, 1
    for d in _slot_sheet_d[slot_type]['hdr']:
        sheet.column_dimensions[xl.get_column_letter(col)].width = d['width']
        if d['width'] != 2:
            excel_util.cell_update(
                sheet,
                row,
                col,
                d.get('buf'),
                font=d['f'],
                align=d['a'],
                border=d['b'],
            )
        col += 1

    # Add the ports
    for port_obj in port_obj_l:

        # Get the control dictionary to determine where and how to display this port
        try:
            port_l = _slot_sheet_d[slot_type]['port'][int(port_obj.r_obj_key().split('/')[1])]
        except (ValueError, TypeError, IndexError, KeyError):
            brcdapi_log.log('ERROR: Programming error encountered. Search the log for EXCEPTION:', echo=True)
            brcdapi_log.exception(['slot_type: ' + slot_type] + class_util.format_obj(port_obj))
            ec = brcddb_common.EXIT_STATUS_ERROR
            continue

        # Add the port to the worksheet
        for d in port_l:
            buf = d.get('buf')
            excel_util.cell_update(
                sheet,
                d['row'],
                d['col'],
                buf(port_obj, d['row']) if callable(buf) else buf,
                font=d.get('f', _std_font),
                align=d.get('a', _align_wrap_c),
                fill=_fill_asic_d[d['asic']],
                border=d.get('b', _border_thin),
                dv=_dv_d[d.get('dv', 'none')](sheet, dv_d)
            )

    return ec



def _port_cli(port_obj, row):
    """Returns CLI for port configurations. See _port_num() for parameter definitions"""
    if port_obj is None:
        return None
    cli_l = list()

    portcfgshow_d = port_obj.r_get('fos_cli/portcfgshow', dict())
    portbuffershow_d = port_obj.r_get('fos_cli/portbuffershow', dict())

    # Locked E-Port (portcfgeport)
    if portcfgshow_d.get('Locked E_Port', '..') == 'ON':
        cli_l.append('portcfgeport $p -p 2')

    # Long distance mode (portcfglongdistance)
    # ToDo - If the only change for LD or LS was the number of reserved credits, that gets missed.
    vc_init = '1' if portcfgshow_d.get('VC Link Init', '..') == 'ON' else '0'
    long_distance = portcfgshow_d.get('Long Distance', '..')
    if long_distance == 'LE':
        cli_l.append('portcfglongdistance $p LE ' + vc_init)
    elif long_distance == 'LD':
        # There is no easy way of know if it was configured for distance or buffers or the length or number of
        # buffers, so just set the distance to 100 Km
        cli_l.append('portcfglongdistance $p LD ' + vc_init + ' -distance 100')
    elif long_distance == 'LS':  # See comments above with LD
        max_resv = max(int(portbuffershow_d.get('max_resv', '20')) - 6, 20)
        cli_l.append('portcfglongdistance $p LS ' + vc_init + ' -buffers ' + str(max_resv))

    # ISL R_RDY Mode (portcfgislmode)
    if portcfgshow_d.get('ISL R_RDY Mode', '..').upper() == 'ON':  # It's always been upper, but just in case...
        cli_l.append('portcfgislmode $p, 1')

    return None if len(cli_l) == 0 else '\n'.join(cli_l)



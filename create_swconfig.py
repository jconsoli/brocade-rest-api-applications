def _chassis_max_rest(chassis_obj):
    """Returns the maximum number of REST sessions as an int. See _chassis_name() for parameter definitions."""
    return chassis_obj.r_get(brcdapi_util.bc_max_rest)


def _chassis_fcr(chassis_obj):
    """Returns Enabled/Disabled to indicate if FCR has been enabled. See _chassis_name() for parameter definitions."""
    fcr = chassis_obj.r_get(brcdapi_util.bc_fcr_en)
    return fcr if fcr is None else 'Enabled' if fcr else 'Disabled'


def _chassis_mod(chassis_obj):
    """Returns the "Message Of The Day". See _chassis_name() for parameter definitions."""
    return chassis_obj.r_get(brcdapi_util.bc_motd)


def _chassis_web_tools(chassis_obj):
    """Returns Enabled/Disabled if Web Tools has been enabled. See _chassis_name() for parameter definitions."""
    wt = chassis_obj.r_get(brcdapi_util.bc_webtools)
    return wt if wt is None else 'Enabled' if wt else 'Disabled'


def _switch_fid(switch_obj):
    """Returns switch fabric id, FID, as int. See _chassis_name() for parameter definitions."""
    return switch_obj.r_fid()


def _switch_fabric_name(switch_obj):
    """Returns fabric user-friendly name as str. See _chassis_name() for parameter definitions."""
    return switch_obj.r_get(brcdapi_util.bfs_fab_user_name)


def _switch_switch_name(switch_obj):
    """Returns switch user-friendly name as str. See _chassis_name() for parameter definitions."""
    return switch_obj.r_get(brcdapi_util.bf_sw_user_name, 'Unknown')


def _switch_did(switch_obj):
    """Returns switch domain id, DID, as hex str with leading 0x. See _chassis_name() for parameter definitions."""
    did = hex(switch_obj.r_get(brcdapi_util.bfs_did, 0)).upper().replace('X', 'x')
    if len(did) == 3:
        did = did.replace('0x', '0x0')
    return did


def _switch_idid(switch_obj):
    """Returns Yes/No if insistent DID is set. See _chassis_name() for parameter definitions."""
    i_did = switch_obj.r_get(brcdapi_util.bfc_idid)
    return i_did if i_did is None else 'Yes' if i_did else 'No'


def _switch_fab_principal(switch_obj):
    """Returns Yes/No if fabric principal has been set. See _chassis_name() for parameter definitions."""

    if switch_obj.r_is_base():
        return None
    principal = switch_obj.r_get(brcdapi_util.bfc_principal_en)
    return principal if principal is None else 'Yes' if principal else 'No'


def _switch_fab_priority(switch_obj):
    """Returns the fabric priority as str (0x leading hex). See _chassis_name() for parameter definitions."""
    if switch_obj.r_is_base():
        return None
    fab_priority = switch_obj.r_get(brcdapi_util.bfc_principal_pri)
    return '0x0a' if fab_priority is None else fab_priority.upper().replace('0X', '0x')


def _switch_xisl(switch_obj):
    """Returns Yes/No if Allow XISL has been set. See _chassis_name() for parameter definitions."""
    xisl = switch_obj.r_get(brcdapi_util.bfc_xisl_en)
    return xisl if xisl is None else 'Yes' if xisl else 'No'


def _switch_login_banner(switch_obj):
    """Returns switch login banner as str. See _chassis_name() for parameter definitions."""
    return switch_obj.r_get(brcdapi_util.bfs_banner)


def _switch_type(switch_obj):
    """Returns switch type as str. See _chassis_name() for parameter definitions."""
    old_base = bool(switch_obj.r_get(brcdapi_util.bfls_base_sw_en.replace('-v2', '')))
    old_ficon = bool(switch_obj.r_get(brcdapi_util.bfls_ficon_mode_en.replace('-v2', '')))

    return 'base' if switch_obj.r_get(brcdapi_util.bfls_base_sw_en, old_base) \
        else 'ficon' if switch_obj.r_get(brcdapi_util.bfls_ficon_mode_en, old_ficon) \
        else 'open'


def _switch_dup_wwn(switch_obj):
    """Returns switch login banner as str. See _chassis_name() for parameter definitions."""
    return switch_obj.r_get(brcdapi_util.bfc_fport_enforce_login)


def _switch_bind_enabled(switch_obj):
    """Returns boolean. True if binding is enabled. See _chassis_name() for parameter definitions.

    This is a little cheessy. I don't have any scripts that bind addresses to some ports in a logical switch and not
    others. I don't know of any practical application where a mix of bound addresses and unbound addresses would make
    sense.
    """
    for port_obj in switch_obj.r_port_objects():
        if port_obj.r_get(brcdapi_util.fc_bind_enabled):
            return 'Yes'
        else:
            break
    return 'No'


def _switch_apt_policy(switch_obj):
    """Returns the routing policy as a str. See _chassis_name() for parameter definitions."""
    apt_policy_d = {'port-based': 'PBR', 'device-based': 'DBR', 'exchange-based': 'EBR'}
    return apt_policy_d[switch_obj.r_get(brcdapi_util.bfs_adv_tuning, 'exchange-based')]


def _switch_port_name(switch_obj):
    """Returns the port name mode as a str. See _chassis_name() for parameter definitions."""
    global _switch_conv_to_name_mode_d

    port_name_mode = _switch_conv_to_name_mode_d.get(switch_obj.r_get(brcdapi_util.bfc_portname_mode))
    if port_name_mode is None:
        brcdapi_log.log('Unknown port name mode: ' + str(port_name_mode))
    elif port_name_mode and switch_obj.r_is_ficon():
        port_name_mode = 'ficon'

    return port_name_mode


def _switch_port_name_format(switch_obj):
    """Returns the port name mode as a str. See _chassis_name() for parameter definitions."""
    return switch_obj.r_get(brcdapi_util.bfc_portname_format) if _switch_port_name(switch_obj) == 'dynamic' else None


def _switch_cup(switch_obj):
    """Returns the state of CUP enable. See _chassis_name() for parameter definitions."""
    return 'Yes' if switch_obj.r_is_cup_enabled() else 'No'


